// 一般的な別の言い方（4=よん, 7=なな, 9=きゅう）で答えを読んだもの
const ONES_ALT = { 1: 'いち', 2: 'に', 3: 'さん', 4: 'よん', 5: 'ご', 6: 'ろく', 7: 'なな', 8: 'はち', 9: 'きゅう' };
function altReading(v) {
  if (v < 10) return ONES_ALT[v];
  const t = Math.floor(v / 10), o = v % 10;
  return (t === 1 ? '' : ONES_ALT[t]) + 'じゅう' + (o ? ONES_ALT[o] : '');
}

function kukuEntry(dan, multiplier) {
  dan = +dan;
  multiplier = +multiplier;
  const d = KUKU_READINGS[dan][multiplier];
  const ttsText = d.pt || d.p;
  const answerTtsText = d.at || d.a;
  return {
    dan,
    multiplier,
    n: multiplier,
    answer: dan * multiplier,
    promptText: d.p,
    ttsText,
    answerText: d.a,
    schoolReading: d.a,
    acceptedReadings: [...new Set([d.a, altReading(dan * multiplier), ...(d.acc || [])])],
    answerTtsText,
    fullText: d.full || `${d.p} ${d.a}`,
    fullTtsText: d.fullTts || `${ttsText}、${answerTtsText}`,
  };
}

